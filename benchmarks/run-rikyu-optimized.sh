#!/usr/bin/env bash
set -euo pipefail
if [[ $# != 2 ]]; then
  echo "Usage: $0 /absolute/path/to/spdyn input.inp (run from the input directory)" >&2
  exit 2
fi
binary="$1"
input="$2"
export OMP_NUM_THREADS=32 OMP_PLACES=cores OMP_PROC_BIND=close
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}"
export GENESIS_INTRA_Y=8 GENESIS_INTRA_TILES=32 GENESIS_INTER_TILES=2
export GENESIS_PME_GPU=1 GENESIS_PME_PACKED=1 GENESIS_PME_PRIORITY=1 GENESIS_PME_SCALE=1
export GENESIS_PME_HOST_THREADS=32 GENESIS_PME_GATHER_LANES=4 GENESIS_PME_CLEAR=1 GENESIS_PME_RAW=0
export GENESIS_DOMAIN_MASK=6 GENESIS_DOMAIN_VERIFY=0
export GENESIS_EXCLUSION_RESET="${GENESIS_EXCLUSION_RESET:-1}" GENESIS_EXCLUSION_VERIFY=0
export GENESIS_EXCLUSION_STATS="${GENESIS_EXCLUSION_STATS:-0}"
export GENESIS_PAIR_HOST=1 GENESIS_PAIR_GPU=1 GENESIS_PAIR_RECORD_PAD=1 GENESIS_PAIR_PINNED=1 GENESIS_PAIR_COMPACT=1
export GENESIS_PAIR_VERIFY=0 GENESIS_PAIR_TIMING=0 GENESIS_PAIR_COMPACT_VERIFY=0
export GENESIS_PAIR_SORT="${GENESIS_PAIR_SORT:-1}" GENESIS_PAIR_SORT_VERIFY=0 GENESIS_PAIR_SORT_POISON=0
export GENESIS_STEP_GPU=1 GENESIS_STEP_VERIFY=0
export GENESIS_FORCE_ASSEMBLY=2 GENESIS_FORCE_BONDED=1 GENESIS_FORCE_RESIDENT=1 GENESIS_FORCE_VERIFY=0
export GENESIS_BONDED_TOTALS="${GENESIS_BONDED_TOTALS:-1}"
export GENESIS_BONDED_TOTALS_STAGED="${GENESIS_BONDED_TOTALS_STAGED:-1}"
export GENESIS_FORCE_CLEAR="${GENESIS_FORCE_CLEAR:-0}"
export GENESIS_TRANSLATION_GPU="${GENESIS_TRANSLATION_GPU:-1}"
export GENESIS_TRANSLATION_REBUILD="${GENESIS_TRANSLATION_REBUILD:-1}"
export GENESIS_MAINT_STATE="${GENESIS_MAINT_STATE:-1}"
export GENESIS_REMAP_PREPARE="${GENESIS_REMAP_PREPARE:-1}"
export GENESIS_NONBOND_MIRROR="${GENESIS_NONBOND_MIRROR:-1}"
export GENESIS_NONBOND_VIRIAL="${GENESIS_NONBOND_VIRIAL:-1}"
export GENESIS_FINAL_REDUCTIONS="${GENESIS_FINAL_REDUCTIONS:-1}"
export GENESIS_FINAL_REDUCTIONS_TREE="${GENESIS_FINAL_REDUCTIONS_TREE:-1}"
export GENESIS_LONG_FORCE="${GENESIS_LONG_FORCE:-1}" GENESIS_LONG_DIRECT="${GENESIS_LONG_DIRECT:-1}"
export GENESIS_STATE_GPU=1 GENESIS_STATE_WORK=1 GENESIS_STATE_HANDOFF=1 GENESIS_STATE_VERIFY=0
export GENESIS_THERMO_GPU=1 GENESIS_THERMO_VERIFY=0
export GENESIS_COORD_GPU=1 GENESIS_COORD_RESIDENT=1 GENESIS_COORD_PME=1 GENESIS_COORD_VERIFY=0
export GENESIS_WATER_GPU=1 GENESIS_WATER_VERIFY=0 GENESIS_WATER_TIMING=0
export GENESIS_MIGRATION_HOST=3 GENESIS_MIGRATION_VERIFY=0
export GENESIS_HGR_GPU=1 GENESIS_HGR_VERIFY=0 GENESIS_HGR_TIMING=0 GENESIS_MAINT_PROBE=0
export GENESIS_BONDED_MIGRATION_GPU="${GENESIS_BONDED_MIGRATION_GPU:-1}" GENESIS_BONDED_MIGRATION_VERIFY=0 GENESIS_BONDED_MIGRATION_TIMING=0
maintenance_gpu="${GENESIS_MAINTENANCE_GPU:-1}"
case "$maintenance_gpu" in 0|1) ;; *) echo 'GENESIS_MAINTENANCE_GPU must be 0 or 1' >&2; exit 2 ;; esac
export GENESIS_INCOMING_GPU="${GENESIS_INCOMING_GPU:-$maintenance_gpu}"
export GENESIS_INCOMING_STORAGE="${GENESIS_INCOMING_STORAGE:-$maintenance_gpu}"
export GENESIS_ATOM_OUTGOING_GPU="${GENESIS_ATOM_OUTGOING_GPU:-$maintenance_gpu}"
export GENESIS_MIGRATION_RESIDENT="${GENESIS_MIGRATION_RESIDENT:-$maintenance_gpu}"
export GENESIS_BONDED_INCOMING_GPU="${GENESIS_BONDED_INCOMING_GPU:-$maintenance_gpu}"
export GENESIS_BONDED_INCOMING_HBM="${GENESIS_BONDED_INCOMING_HBM:-$maintenance_gpu}"
export GENESIS_BONDED_RESIDENCY="${GENESIS_BONDED_RESIDENCY:-$maintenance_gpu}"
export GENESIS_BONDED_INCOMING_COOPERATIVE="${GENESIS_BONDED_INCOMING_COOPERATIVE:-$maintenance_gpu}"
export GENESIS_BONDED_HOST_MIRROR="${GENESIS_BONDED_HOST_MIRROR:-$maintenance_gpu}"
export GENESIS_EXCLUSION_GPU="${GENESIS_EXCLUSION_GPU:-$maintenance_gpu}"
export GENESIS_PAIR_PREPARE_GPU="${GENESIS_PAIR_PREPARE_GPU:-$maintenance_gpu}"
export GENESIS_IMPROPER_OUTGOING_GPU="${GENESIS_IMPROPER_OUTGOING_GPU:-$maintenance_gpu}"
export GENESIS_FORCE_TOPOLOGY_GPU="${GENESIS_FORCE_TOPOLOGY_GPU:-$maintenance_gpu}"
export GENESIS_METADATA_IMPORT="${GENESIS_METADATA_IMPORT:-$maintenance_gpu}"
export GENESIS_STATE_CYCLE="${GENESIS_STATE_CYCLE:-$maintenance_gpu}"
export GENESIS_PACK_RESIDENT="${GENESIS_PACK_RESIDENT:-$maintenance_gpu}"
export GENESIS_OBSERVABLES_GPU="${GENESIS_OBSERVABLES_GPU:-$maintenance_gpu}"
case "${GENESIS_OPT_VERIFY:-0}" in
  0) ;;
  1) export GENESIS_FORCE_VERIFY="${GENESIS_OPT_FORCE_VERIFY:-1}"
     export GENESIS_STATE_VERIFY=1 GENESIS_THERMO_VERIFY=1 GENESIS_COORD_VERIFY=1
     export GENESIS_EXCLUSION_VERIFY=1 GENESIS_PAIR_VERIFY=1 GENESIS_PAIR_COMPACT_VERIFY=1
     export GENESIS_PAIR_SORT_VERIFY=1
     export GENESIS_BONDED_MIGRATION_VERIFY=1
     export GENESIS_BONDED_TOTALS=2
     export GENESIS_LONG_FORCE=2
     export GENESIS_TRANSLATION_GPU=2
     export GENESIS_TRANSLATION_REBUILD=2
     export GENESIS_MAINT_STATE=2
     export GENESIS_REMAP_PREPARE=2
     export GENESIS_NONBOND_MIRROR=2
     export GENESIS_NONBOND_VIRIAL=2
     export GENESIS_FINAL_REDUCTIONS=2
     export GENESIS_INCOMING_GPU=2
     export GENESIS_ATOM_OUTGOING_GPU=2
     export GENESIS_BONDED_INCOMING_GPU=2
     export GENESIS_EXCLUSION_GPU=2
     export GENESIS_PAIR_PREPARE_GPU=2
     export GENESIS_IMPROPER_OUTGOING_GPU=2
     export GENESIS_FORCE_TOPOLOGY_GPU=2
     export GENESIS_METADATA_IMPORT=2
     export GENESIS_STATE_CYCLE=2
     export GENESIS_PACK_RESIDENT=2
     export GENESIS_OBSERVABLES_GPU=2
     export GENESIS_WATER_VERIFY=1 GENESIS_MIGRATION_VERIFY=1 GENESIS_HGR_VERIFY=1 ;;
  *) echo 'GENESIS_OPT_VERIFY must be 0 or 1' >&2; exit 2 ;;
esac
mpirun -n 1 --map-by ppr:1:node:PE=32 --bind-to core "$binary" "$input"
