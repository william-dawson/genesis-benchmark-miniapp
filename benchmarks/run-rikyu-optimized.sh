#!/usr/bin/env bash
set -euo pipefail
if [[ $# != 2 ]]; then
  echo "Usage: $0 /absolute/path/to/spdyn input.inp (run from the input directory)" >&2
  exit 2
fi
binary="$1"
input="$2"
export OMP_NUM_THREADS=32 OMP_PLACES=cores OMP_PROC_BIND=close
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}"
export GENESIS_INTRA_Y=8 GENESIS_INTRA_TILES=32 GENESIS_INTER_TILES=2
export GENESIS_PME_GPU=1 GENESIS_PME_PACKED=1 GENESIS_PME_PRIORITY=1 GENESIS_PME_SCALE=1
export GENESIS_PME_HOST_THREADS=32 GENESIS_PME_GATHER_LANES=4 GENESIS_PME_CLEAR=1 GENESIS_PME_RAW=0
export GENESIS_DOMAIN_MASK=6 GENESIS_DOMAIN_VERIFY=0
export GENESIS_EXCLUSION_RESET="${GENESIS_EXCLUSION_RESET:-1}" GENESIS_EXCLUSION_VERIFY=0
export GENESIS_EXCLUSION_STATS="${GENESIS_EXCLUSION_STATS:-0}"
export GENESIS_PAIR_HOST=1 GENESIS_PAIR_GPU=1 GENESIS_PAIR_RECORD_PAD=1 GENESIS_PAIR_PINNED=1 GENESIS_PAIR_COMPACT=1
export GENESIS_PAIR_VERIFY=0 GENESIS_PAIR_TIMING=0 GENESIS_PAIR_COMPACT_VERIFY=0
export GENESIS_STEP_GPU=1 GENESIS_STEP_VERIFY=0
export GENESIS_FORCE_ASSEMBLY=2 GENESIS_FORCE_BONDED=1 GENESIS_FORCE_RESIDENT=1 GENESIS_FORCE_VERIFY=0
export GENESIS_STATE_GPU=1 GENESIS_STATE_WORK=1 GENESIS_STATE_HANDOFF=1 GENESIS_STATE_VERIFY=0
export GENESIS_THERMO_GPU=1 GENESIS_THERMO_VERIFY=0
export GENESIS_COORD_GPU=1 GENESIS_COORD_RESIDENT=1 GENESIS_COORD_PME=1 GENESIS_COORD_VERIFY=0
export GENESIS_WATER_GPU=1 GENESIS_WATER_VERIFY=0 GENESIS_WATER_TIMING=0
export GENESIS_MIGRATION_HOST=3 GENESIS_MIGRATION_VERIFY=0
export GENESIS_HGR_GPU=1 GENESIS_HGR_VERIFY=0 GENESIS_HGR_TIMING=0 GENESIS_MAINT_PROBE=0
case "${GENESIS_OPT_VERIFY:-0}" in
  0) ;;
  1) export GENESIS_FORCE_VERIFY=1 GENESIS_STATE_VERIFY=1 GENESIS_THERMO_VERIFY=1 GENESIS_COORD_VERIFY=1
     export GENESIS_EXCLUSION_VERIFY=1 GENESIS_PAIR_VERIFY=1 GENESIS_PAIR_COMPACT_VERIFY=1
     export GENESIS_WATER_VERIFY=1 GENESIS_MIGRATION_VERIFY=1 GENESIS_HGR_VERIFY=1 ;;
  *) echo 'GENESIS_OPT_VERIFY must be 0 or 1' >&2; exit 2 ;;
esac
mpirun -n 1 --map-by ppr:1:node:PE=32 --bind-to core "$binary" "$input"
